@lru_cache(maxsize=1)
def traditional_to_simplified_map() -> dict[str, str]:
    mapping = dict(MANUAL_TRAD_TO_SIMP)
    if not DEFAULT_CEDICT_PATH.exists():
        return mapping
    for line in DEFAULT_CEDICT_PATH.read_text(encoding="utf-8", errors="ignore").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        parts = stripped.split(maxsplit=2)
        if len(parts) < 2:
            continue
        traditional, simplified = parts[0], parts[1]
        if traditional and simplified and traditional != simplified:
            mapping.setdefault(traditional, simplified)
            if len(traditional) == 1 and len(simplified) == 1:
                mapping.setdefault(traditional, simplified)
    return mapping


def simplify_text(text: str) -> str:
    mapping = traditional_to_simplified_map()
    if text in mapping:
        return mapping[text]
    return "".join(mapping.get(char, char) for char in text)


def han_variants(term: str) -> list[str]:
    cleaned = str(term or "").strip()
    if not cleaned:
        return []
    simplified = simplify_text(cleaned)
    variants = [cleaned]
    if simplified and simplified != cleaned:
        variants.append(simplified)
    return variants
